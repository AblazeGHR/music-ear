#!/usr/bin/env python
# build-music-glyphs.py — extract the handful of Bravura glyphs the sight-reading
# renderer needs and write them as inline SVG paths (js/music-glyphs.js).
#
# Bravura is the SMuFL reference font by Steinberg Media Technologies, licensed
# under the SIL Open Font License 1.1 (see assets/fonts/Bravura-OFL.txt). The
# font itself is not shipped; only these outline paths are inlined, which keeps
# the app offline and deterministic (no font loading, no fallback glyphs).
#
# The font is read from .cache/fonts/Bravura.otf, downloading it when missing.
# Run: E:/software/miniforge/python.exe scripts/build-music-glyphs.py

import json
import pathlib
import urllib.request

from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen

ROOT = pathlib.Path(__file__).resolve().parent.parent
CACHE = ROOT / '.cache' / 'fonts'
FONT = CACHE / 'Bravura.otf'
OUT = ROOT / 'js' / 'music-glyphs.js'
URL = 'https://raw.githubusercontent.com/steinbergmedia/bravura/master/redist/otf/Bravura.otf'

GLYPHS = {
    'gClef': 0xE050,
    'timeSig4': 0xE084,
    'noteheadWhole': 0xE0A2,
    'noteheadHalf': 0xE0A3,
    'noteheadBlack': 0xE0A4,
    'augmentationDot': 0xE1E7,
    'flag8thUp': 0xE240,
    'flag8thDown': 0xE241,
}


def ensure_font():
    if FONT.exists():
        return
    CACHE.mkdir(parents=True, exist_ok=True)
    print(f'downloading {URL}')
    urllib.request.urlretrieve(URL, FONT)


def main():
    ensure_font()
    font = TTFont(FONT)
    upem = font['head'].unitsPerEm
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()

    out = {}
    for name, cp in GLYPHS.items():
        glyph_name = cmap[cp]
        g = glyphs[glyph_name]
        pen = SVGPathPen(glyphs)
        g.draw(pen)
        bounds = BoundsPen(glyphs)
        g.draw(bounds)
        out[name] = {
            'path': pen.getCommands(),
            'adv': g.width,
            'bbox': [round(v, 3) for v in (bounds.bounds or (0, 0, 0, 0))],
        }

    body = json.dumps(out, indent=2, ensure_ascii=False)
    OUT.write_text(
        '// music-glyphs.js — Bravura (SMuFL) outlines, generated by\n'
        '// scripts/build-music-glyphs.py. Do not edit by hand.\n'
        '// Bravura © Steinberg Media Technologies GmbH, SIL OFL 1.1\n'
        '// (assets/fonts/Bravura-OFL.txt). Coordinates are font units, y up:\n'
        '// render with transform="translate(x y) scale(s -s)".\n\n'
        f'export const GLYPH_UPEM = {upem};\n'
        f'export const MUSIC_GLYPHS = {body};\n',
        encoding='utf-8', newline='\n')
    print(f'wrote {OUT} ({OUT.stat().st_size} bytes), upem {upem}')


if __name__ == '__main__':
    main()
